import 'server-only'
import type { NextResponse } from 'next/server'
import type { InsightResult } from '@/features/ai-insights/insight-repository'
import type { InsightFeature } from '@/features/ai-insights/schemas'
import { captureError } from '@/lib/observability/capture-error'
import { AiError, type AiFailure } from '@/server/ai/llm'
import { failure, json } from './json-route'

// The one JSON shape every AI insight endpoint returns, and the one mapping
// from AI failures to statuses. AI content is always labelled as such and
// carries the reminder that official scores are Dojo's own; a provider's
// error, key or internal message never reaches the client.

const LABELS: Record<InsightFeature, string> = {
	session_analysis: 'AI-powered insight',
	assessment_explanation: 'AI-powered insight',
	attempt_feedback: 'Personalized AI feedback',
	challenge_example: 'AI-generated example',
	recommendation_explanation: 'AI-powered insight'
}

const NOTICE =
	'Generated by AI from your Dojo data. It may be wrong, and it never changes your official Dojo scores, which come from deterministic rules.'

export function insightJson<T>(
	result: InsightResult<T> | null,
	status = 200,
	extra: Record<string, unknown> = {}
): NextResponse {
	if (result == null) return json({ insight: null, ...extra }, status)
	const { insight, cached } = result
	return json(
		{
			insight: {
				id: insight.id,
				feature: insight.feature,
				label: LABELS[insight.feature],
				notice: NOTICE,
				aiGenerated: true,
				model: insight.model,
				promptVersion: insight.promptVersion,
				createdAt: insight.createdAt.toISOString(),
				cached,
				content: insight.output
			},
			...extra
		},
		status
	)
}

const RESPONSES: Record<AiFailure, { status: number; message: string }> = {
	disabled: { status: 503, message: 'AI insights are not available right now.' },
	quota_exceeded: {
		status: 429,
		message: "You've reached today's limit for AI insights. Try again tomorrow."
	},
	rate_limited: {
		status: 503,
		message:
			'The free AI model is busy or its usage limit was reached. Try again in a few minutes; the rest of Dojo works as usual.'
	},
	payment_required: {
		status: 503,
		message:
			'AI insights are paused: the AI usage quota is used up. The rest of Dojo works as usual.'
	},
	unavailable: { status: 503, message: 'The AI service is unavailable. Try again later.' },
	timeout: { status: 503, message: 'The AI service took too long to answer. Try again.' },
	auth: { status: 503, message: 'The AI service is unavailable. Try again later.' },
	invalid_output: {
		status: 502,
		message: "The AI couldn't produce a usable answer this time. Try again."
	},
	refused: { status: 502, message: "The AI couldn't produce an answer for this. Try again." }
}

/** The response for an AI failure, or null if `error` is not one (let it propagate). */
export function aiFailureResponse(error: unknown): NextResponse | null {
	if (!(error instanceof AiError)) return null
	// A rejected key or an answer that never fits the schema is ours to fix:
	// report it. Outages, limits and switches are expected and only answered.
	if (
		error.failure === 'auth' ||
		error.failure === 'payment_required' ||
		error.failure === 'invalid_output'
	) {
		captureError(error, { failure: error.failure })
	}
	const { status, message } = RESPONSES[error.failure]
	return failure(status, message)
}

/** Runs an endpoint body, answering AI failures with their mapped status. */
export async function answeringAiFailures(run: () => Promise<NextResponse>): Promise<NextResponse> {
	try {
		return await run()
	} catch (error) {
		const response = aiFailureResponse(error)
		if (response != null) return response
		throw error
	}
}

/** 201 for a fresh generation, 200 for a stored or reused one. */
export const statusOf = (result: InsightResult<unknown> | null) =>
	result != null && !result.cached ? 201 : 200
